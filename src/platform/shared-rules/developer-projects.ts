import {
  anyDirectory,
  atPath,
  Category,
  containsMarkerFile,
  defineRule,
  deleteRegenerable,
  namedAnywhere,
  OwnerToolId,
  parentContainsMarkerFile,
  RuleId,
  runOwnerTool,
  SafetyLevel,
  type Rule,
} from "../../domain/index.ts";
import { ProjectFolder, ProjectMarker, SharedPaths } from "./shared-paths.ts";

export const developerProjectRules: readonly Rule[] = [
  defineRule({
    id: RuleId.NodeModules,
    category: Category.DeveloperFiles,
    locator: namedAnywhere(ProjectFolder.NodeModules),
    conditions: [parentContainsMarkerFile(ProjectMarker.NodePackage)],
    safety: SafetyLevel.Regenerable,
    remedy: deleteRegenerable(),
  }),
  defineRule({
    id: RuleId.NextJsBuildCache,
    category: Category.DeveloperFiles,
    locator: namedAnywhere(ProjectFolder.NextJsBuild),
    conditions: [parentContainsMarkerFile(ProjectMarker.NodePackage)],
    safety: SafetyLevel.Regenerable,
    remedy: deleteRegenerable(),
  }),
  defineRule({
    id: RuleId.RustBuildOutput,
    category: Category.DeveloperFiles,
    locator: namedAnywhere(ProjectFolder.RustBuildOutput),
    conditions: [parentContainsMarkerFile(ProjectMarker.RustCrate)],
    safety: SafetyLevel.Regenerable,
    remedy: deleteRegenerable(),
  }),
  defineRule({
    id: RuleId.PythonVirtualEnvironment,
    category: Category.DeveloperFiles,
    locator: anyDirectory(),
    conditions: [containsMarkerFile(ProjectMarker.PythonVirtualEnvironment)],
    safety: SafetyLevel.Regenerable,
    remedy: deleteRegenerable(),
  }),
  defineRule({
    id: RuleId.PythonBytecodeCache,
    category: Category.DeveloperFiles,
    locator: namedAnywhere(ProjectFolder.PythonBytecodeCache),
    safety: SafetyLevel.Regenerable,
    remedy: deleteRegenerable(),
  }),
  defineRule({
    id: RuleId.NpmCache,
    category: Category.DeveloperFiles,
    locator: atPath(SharedPaths.npmCache),
    safety: SafetyLevel.SafeViaOwnerTool,
    remedy: runOwnerTool(OwnerToolId.NpmCacheClean),
  }),
  defineRule({
    id: RuleId.GradleCaches,
    category: Category.DeveloperFiles,
    locator: atPath(SharedPaths.gradleCaches),
    safety: SafetyLevel.Regenerable,
    remedy: deleteRegenerable(),
  }),
  defineRule({
    id: RuleId.MavenRepository,
    category: Category.DeveloperFiles,
    locator: atPath(SharedPaths.mavenRepository),
    safety: SafetyLevel.Regenerable,
    remedy: deleteRegenerable(),
  }),
];
